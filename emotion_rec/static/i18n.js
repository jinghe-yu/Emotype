  function label(value) {
    if (getCurrentLang() === "zh" || typeof value !== "string") return value;
    var direct = EMOTION_LABELS_EN[value.trim()];
    if (direct) return direct;
    // Preserve v2-new's compound labels without translating custom user text.
    return value.split(/(\/|／|、|，|,|·|\s+\+\s+)/g).map(function (part) {
      var translated = EMOTION_LABELS_EN[part.trim()];
      return translated ? part.replace(part.trim(), translated) : part;
    }).join("");
  }

  function getCurrentLang() {
    try { return localStorage.getItem("emomirror.lang") === "zh" ? "zh" : "en"; } catch (e) { return "en"; }
  }

  function t(key) {
    var lang = getCurrentLang();
    return (I18N[lang] || I18N.en)[key] || I18N.en[key] || key;
  }

  function applySharedI18n() {
    var lang = getCurrentLang();
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    });
    document.querySelectorAll("[data-i18n-value]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-value");
      if (key) el.value = t(key);
    });
    applyCopy();
  }

  // Static, app-owned copy only: editors and saved user content are never traversed.
  function applyCopy() {
    document.querySelectorAll("[data-ui-copy]").forEach(function (el) {
      el.textContent = text(el.getAttribute("data-ui-copy"));
    });
    ["placeholder", "title", "alt", "aria-label"].forEach(function (attr) {
      document.querySelectorAll("[data-ui-" + attr + "]").forEach(function (el) {
        el.setAttribute(attr, text(el.getAttribute("data-ui-" + attr)));
      });
    });
  }

